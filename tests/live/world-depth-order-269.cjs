'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const path=require('node:path');
const source=fs.readFileSync(path.resolve(__dirname,'../../haigen.html'),'utf8');
const expect=(pattern,message)=>assert.match(source,pattern,message);
expect(/drawables\.forEach\(\(o,i\)=>\{o\.depthOrder=i\}\)/,'world drawables must have stable insertion index');
expect(/drawables\.sort\(\(a,b\)=>a\.y-b\.y\|\|a\.depthOrder-b\.depthOrder\)/,'world drawables must sort by foot Y then insertion order');
expect(/woodlandDeer\.filter\([\s\S]*?\.map\(a=>\(\{y:a\.y,draw:/,'woodland deer must enter world depth queue');
expect(/regionalWildlife\.filter\([\s\S]*?\.map\(a=>\(\{y:a\.y,draw:/,'regional wildlife must enter world depth queue');
expect(/drawables\.push\(\{y:trollStumpHome\.y-2,draw:drawTrollStump\}\)/,'stump must remain in world depth queue');
expect(/\{y:state\.y\+1,draw:/,'Haigen must remain in world depth queue');
expect(/\.\.\.companions\.map\(c=>\(\{y:c\.y,draw:/,'companions must remain in world depth queue');
const sort=(items)=>items.map((item,i)=>({...item,depthOrder:i})).sort((a,b)=>a.y-b.y||a.depthOrder-b.depthOrder);
assert.deepEqual(sort([{id:'deer',y:90},{id:'rock',y:100}]).map(x=>x.id),['deer','rock']);
assert.deepEqual(sort([{id:'rock',y:100},{id:'deer',y:110}]).map(x=>x.id),['rock','deer']);
assert.deepEqual(sort([{id:'deer',y:2200},{id:'stump',y:2198}]).map(x=>x.id),['stump','deer']);
assert.deepEqual(sort([{id:'deer',y:2100},{id:'stump',y:2198}]).map(x=>x.id),['deer','stump']);
assert.deepEqual(sort([{id:'a',y:100},{id:'b',y:100},{id:'c',y:100}]).map(x=>x.id),['a','b','c']);
console.log('World depth queue source and ordering regression passed');
