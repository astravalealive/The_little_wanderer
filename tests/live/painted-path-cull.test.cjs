'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const html=fs.readFileSync('haigen.html','utf8');
const start=html.indexOf('function path(){'),end=html.indexOf('\nfunction ellipse(',start);
assert(start>=0&&end>start,'path renderer exists');
const body=html.slice(start,end);
assert(body.includes('if(paintedTrailsReady)'),'painted trail branch remains');
assert(body.includes('ctx.drawImage(paintedTrails,0,0,7800,7800)'),'painted trail image remains');
assert(body.includes('drawWoodlandPathEdges();return'),'natural path edge detail remains');
const paintedBranch=body.slice(body.indexOf('if(paintedTrailsReady)'),body.indexOf('drawWoodlandPathEdges();return'));
assert(!paintedBranch.includes('roadTrace('),'no geometric road strokes over painted trails');
assert(!paintedBranch.includes('ctx.strokeStyle'),'no dark soil glaze over painted trails');
assert(!paintedBranch.includes('if(cam.x+halfW>0'),'obsolete overlay culling removed');
assert(body.includes('const bands='),'fallback road rendering preserved');
console.log('PASS: painted trails retain natural edges without geometric overlay; fallback preserved');
